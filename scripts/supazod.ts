import { writeFile } from "node:fs/promises";
import { join } from "node:path";

import { format } from "prettier";
import { generateContent } from "supazod";

/**
 * Generates Zod schemas from Supabase database types and applies custom formatting.
 *
 * This script:
 * 1. Generates schemas from database.types.ts
 * 2. Cleans up the generated output
 * 3. Adds TypeScript type exports for each schema
 * 4. Formats the result with prettier
 */
async function main(): Promise<void> {
  const inputPath = join(
    process.cwd(),
    "src",
    "lib",
    "supabase",
    "database.types.ts",
  );
  const outputPath = join(
    process.cwd(),
    "src",
    "lib",
    "supabase",
    "schemas.ts",
  );

  const content = await generateContent({
    // Core configuration
    input: inputPath,
    output: outputPath,
    typesOutput: outputPath,
    schema: ["public"],

    // Processing options
    processDependencies: true,
    verbose: false,
    keepComments: true,
    skipParseJSDoc: false,

    // Naming conventions
    getSchemaName: (name) => name.replace(/^Public|Schema$/g, ""),
    enumFormatter: (name) => `${name}Enum`,
    compositeTypeFormatter: (name) => `${name}Type`,
    functionFormatter: (name, type) => `${name}${type}`,
    tableOrViewFormatter: (name, operation) => `${name}${operation}`,

    // Type name transformer for PascalCase conversion
    typeNameTransformer: (name) =>
      name
        .split("_")
        .map(
          (part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase(),
        )
        .join(""),
  });

  // Post-process the generated content
  const processedContent = content.rawSchemasFileContent
    // Remove the generated by supazod comment
    .replace(
      /\/\*\s*\n\s*\*\s*=+\s*\n\s*\*\s*\|\s*GENERATED BY SUPAZOD\s*\|\s*\n\s*\*\s*=+\s*\n\s*\*\/\s*\n/g,
      "",
    )
    // Replace the Json import with our custom JsonValue
    .replace(
      /import\s*{\s*type\s*Json\s*}\s*from\s*["']\.\/database\.types["'];?/g,
      '\nimport { JsonValue as Json } from "~/lib/schemas/utils";',
    )
    // Remove the Json schema definition
    .replace(
      /^export const Json: z\.ZodSchema<Json> = z\.lazy\(\(\) =>[\s\S]*?\.nullable\(\),[\s\S]*?\);/ms,
      "",
    )
    // Add TypeScript type exports for each schema
    .replace(
      /(export const (\w+) = z\.[^;]+;)/g,
      "$1\nexport type $2 = z.infer<typeof $2>;",
    );

  // Format the final output with prettier
  const formattedContent = await format(processedContent, {
    parser: "typescript",
  });

  // Write the result to the output file
  await writeFile(outputPath, formattedContent);

  console.log(`✅ Successfully generated Zod schemas at ${outputPath}`);
}

// Execute the main function and handle any errors
void main().catch((error) => {
  console.error("❌ Error generating Zod schemas:", error);
  process.exit(1);
});
